export function seedBuiltinSnippets(): void {
  const count = repo.countBuiltin();
  if (count > 0) return;

  for (const snippet of BUILTIN_SNIPPETS) {
    repo.create({
      projectId: null,
      name: snippet.name,
      category: snippet.category,
      content: snippet.content,
      isBuiltin: 1,
      sortOrder: snippet.sortOrder,
    });
  }

  console.log(`[Xbboook] Seeded ${BUILTIN_SNIPPETS.length} builtin snippet templates`);
}